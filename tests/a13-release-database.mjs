import assert from 'node:assert/strict';
import { createDatabase, userId } from './learning-database.mjs';

const db = await createDatabase();
const otherUser = '22222222-2222-4222-8222-222222222222';
const stamp = '2026-11-09T10:00:00.000Z';
const keyFor = (lesson, skill) => `deutsch-trainer-release-course-v1-${lesson}-${skill}`;
const save = (key, state, owner = userId) => db.query(`insert into public.learner_lesson_states(user_id,lesson_key,state) values($1,$2,$3) on conflict(user_id,lesson_key) do update set state=excluded.state`, [owner,key,state]);
const read = async key => (await db.query('select state from public.learner_lesson_states where lesson_key=$1',[key])).rows[0]?.state;
const empty = () => ({version:1,learned:[],cursor:0,active:null,attempts:[],round:null});
try {
  const catalog = (await db.query('select * from public.release_course_tasks t where not exists (select 1 from public.release_practice_metadata m where m.lesson_id=t.lesson_id and m.skill=t.skill and m.task_id=t.task_id and m.is_extension) order by lesson_id,skill,task_id')).rows;
  assert.equal(catalog.length,372,'real generated catalog is installed');
  const courses = new Map();
  for(const task of catalog) courses.set(keyFor(task.lesson_id,task.skill),task);
  assert.equal(courses.size,12);
  for(const [key,task] of courses){
    await save(key,empty());
    const draft = {...empty(),learned:task.required_card_ids,active:{taskId:task.task_id,draft:'ร่างที่ยังไม่ส่ง',helpUsed:true,startedAt:stamp,selectionReason:'new'},round:{id:'round',startedAt:stamp,limit:10}};
    await save(key,draft);
    assert.deepEqual(await read(key),draft,'draft and round survive account persistence');
    const attempt={id:`first-${task.task_id}`,taskId:task.task_id,response:task.accepted_answers[0],correct:true,helpUsed:true,submittedAt:stamp,selectionReason:'new'};
    const answered={...draft,active:null,attempts:[attempt]};
    await save(key,answered);
    assert.deepEqual(await read(key),answered);
    await assert.rejects(save(key,{...answered,attempts:[]}),/cannot be removed/);
    await assert.rejects(save(key,{...answered,attempts:[{...attempt,response:'changed',correct:false}]}),/immutable/);
    await assert.rejects(save(key,{...answered,attempts:[{...attempt,helpUsed:false}]}),/immutable/);
    await assert.rejects(save(key,{...answered,attempts:[attempt,{...attempt,id:'fabricated',response:'__wrong__',correct:true}]}),/grading/);
    await assert.rejects(save(key,{...answered,attempts:[attempt,{...attempt,id:'unknown',taskId:'unknown'}]}),/Unknown course task/);
    const retry={...attempt,id:`retry-${task.task_id}`,response:'__wrong__',correct:false};
    await save(key,{...answered,attempts:[attempt,retry]});
    assert.deepEqual((await read(key)).attempts,[attempt,retry],'first retained alongside retry');
  }
  await db.exec(`set request.jwt.claim.sub='${otherUser}'`);
  assert.equal((await db.query("select * from public.learner_lesson_states where lesson_key like 'deutsch-trainer-release-course-v1-%'")).rows.length,0,'another account cannot read original states');
  const task=catalog[0],key=keyFor(task.lesson_id,task.skill);
  await assert.rejects(save(key,{...empty(),active:{taskId:task.task_id,draft:'',helpUsed:false,startedAt:stamp}},otherUser),/not learned|Invalid active/);
  await assert.rejects(save(key,{...empty(),learned:['unknown-card']},otherUser),/Unknown release course card/);
  await assert.rejects(save(key,empty(),userId),/row-level security/);
  await save(key,empty(),otherUser);
  assert.deepEqual(await read(key),empty(),'second account has independent state');
  await db.exec(`set request.jwt.claim.sub='${userId}'`);
  assert.equal((await read(key)).attempts.length,2,'second account cannot erase original first/retry');
  const helpedTask=catalog[0],helpedKey=keyFor(helpedTask.lesson_id,helpedTask.skill);
  const initialHelp=await read(helpedKey);
  const activeHelp={...initialHelp,active:{taskId:helpedTask.task_id,draft:'remote help',helpUsed:true,startedAt:stamp,selectionReason:'new'}};
  await save(helpedKey,activeHelp);
  await save(helpedKey,{...activeHelp,active:{...activeHelp.active,helpUsed:false}});
  assert.equal((await read(helpedKey)).active.helpUsed,true,'stale Learn active retains remote help');
  const afterHelp=await read(helpedKey);
  const staleLearn={id:'stale-learn-help',taskId:helpedTask.task_id,response:helpedTask.accepted_answers[0],correct:true,helpUsed:false,submittedAt:stamp,selectionReason:'new'};
  await save(helpedKey,{...afterHelp,active:null,attempts:[...afterHelp.attempts,staleLearn]});
  assert.equal((await read(helpedKey)).attempts.at(-1).helpUsed,true,'stale Learn first inherits active help without blocking');
  const unicodeTask = catalog.find(q => q.accepted_answers.some(answer => /[äöüÄÖÜ]/.test(answer)));
  assert.ok(unicodeTask,'catalog includes umlaut answers');
  const unicodeKey = keyFor(unicodeTask.lesson_id,unicodeTask.skill);
  const unicodeState = await read(unicodeKey);
  const unicodeAttempt = {id:'unicode-normalization',taskId:unicodeTask.task_id,response:'\u00a0\t'+unicodeTask.accepted_answers[0].normalize('NFD')+'\u2007\n',correct:true,helpUsed:false,submittedAt:stamp,selectionReason:'normalization'};
  await save(unicodeKey,{...unicodeState,learned:[...new Set([...unicodeState.learned,...unicodeTask.required_card_ids])],attempts:[...unicodeState.attempts,unicodeAttempt]});
  assert.equal((await read(unicodeKey)).attempts.at(-1).response,unicodeAttempt.response,'NFC and ECMAScript whitespace normalize grading without changing saved response');
  const spellingTask=catalog.find(q=>q.case_sensitive && /^[A-ZÄÖÜ]/.test(q.accepted_answers[0]));
  assert.ok(spellingTask,'spelling catalog marks case-sensitive orthography');
  const spellingKey=keyFor(spellingTask.lesson_id,spellingTask.skill);
  const spellingState=await read(spellingKey);
  const wrongCase=spellingTask.accepted_answers[0][0].toLocaleLowerCase('de')+spellingTask.accepted_answers[0].slice(1);
  const spellingAttempt={id:'spelling-case',taskId:spellingTask.task_id,response:wrongCase,correct:false,helpUsed:false,submittedAt:stamp,selectionReason:'orthography'};
  const withSpelling={...spellingState,learned:[...new Set([...spellingState.learned,...spellingTask.required_card_ids])],attempts:[...spellingState.attempts,spellingAttempt]};
  await assert.rejects(save(spellingKey,{...withSpelling,attempts:[...spellingState.attempts,{...spellingAttempt,correct:true}]}),/grading/);
  await save(spellingKey,withSpelling);
  const spellingUnicode=catalog.find(q=>q.case_sensitive && /[äöüÄÖÜ]/.test(q.accepted_answers[0]));
  assert.ok(spellingUnicode);
  const spellingUnicodeKey=keyFor(spellingUnicode.lesson_id,spellingUnicode.skill);
  const beforeUnicode=await read(spellingUnicodeKey);
  const exactUnicode={...spellingAttempt,id:'spelling-nfc',taskId:spellingUnicode.task_id,response:'\u00a0'+spellingUnicode.accepted_answers[0].normalize('NFD')+'\u2007',correct:true};
  await save(spellingUnicodeKey,{...beforeUnicode,learned:[...new Set([...beforeUnicode.learned,...spellingUnicode.required_card_ids])],attempts:[...beforeUnicode.attempts,exactUnicode]});
  console.log('A13 release database: 12 ordinary-account states, generated grading, drafts/resume, firsts, prerequisites and account isolation passed.');
} finally { await db.close(); }
