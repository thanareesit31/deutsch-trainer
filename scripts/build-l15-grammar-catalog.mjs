import {writeFile} from 'node:fs/promises';
import {l15GuidedCards,l15GuidedTasks} from '../src/lib/l15-grammar-catalog.ts';
import {l15GrammarLearningCards} from '../src/data/l15-grammar-learning.ts';
const quote=value=>"'"+String(value).replaceAll("'","''")+"'";
const json=value=>quote(JSON.stringify(value))+'::jsonb';
const cards=l15GuidedCards.map((card,index)=>({index,id:card.id,key:index===0?'owner':l15GrammarLearningCards[index-1].id,pages:index===0?3:l15GrammarLearningCards[index-1].pages.length+1}));
const sql=`-- Generated by node --import tsx scripts/build-l15-grammar-catalog.mjs. Additive, preserves existing definitions/history.
begin;
create table if not exists public.l15_grammar_learning_cards(card_index integer primary key,card_id text not null unique,card_key text not null unique,teaching_pages integer not null check(teaching_pages>0));
alter table public.l15_grammar_learning_cards enable row level security;
drop policy if exists "Read L15 grammar cards" on public.l15_grammar_learning_cards;
create policy "Read L15 grammar cards" on public.l15_grammar_learning_cards for select to authenticated using(true);
grant select on public.l15_grammar_learning_cards to authenticated;
insert into public.l15_grammar_learning_cards(card_index,card_id,card_key,teaching_pages) values
${cards.map(card=>`(${card.index},${quote(card.id)},${quote(card.key)},${card.pages})`).join(',\n')}
on conflict(card_index) do nothing;
insert into public.release_course_cards(lesson_id,skill,card_id) values
${cards.map(card=>`('L15','grammar',${quote(card.id)})`).join(',\n')}
on conflict(lesson_id,skill,card_id) do nothing;
alter table public.release_course_tasks add column if not exists guided_definition jsonb;
insert into public.release_course_tasks(lesson_id,skill,task_id,version,accepted_answers,required_card_ids,case_sensitive,definition,guided_definition) values
${l15GuidedTasks.map(task=>{const card=cards.find(card=>task.requiredCardIds.includes(card.id));const responseKey=card.index===0?(task.id.endsWith('01')?'anna':'tom'):task.id;const definition={id:task.id,version:task.version,targetId:task.targetId,topicId:'L15-grammar',subskill:task.subskill,kind:task.kind==='write'?'cloze':task.kind,acceptedAnswers:task.acceptedAnswers};return `('L15','grammar',${quote(task.id)},1,${json(task.acceptedAnswers)},${json(task.requiredCardIds)},false,${json(definition)},${json({kind:task.kind,options:task.options,tokens:task.tokens,cardIndex:card.index,responseKey})})`;}).join(',\n')}
on conflict(lesson_id,skill,task_id,version) do nothing;
insert into public.release_practice_metadata(lesson_id,skill,task_id,context_id,family_id,stage,unlock,is_extension) values
${l15GuidedTasks.map(task=>`('L15','grammar',${quote(task.id)},${quote(task.id)},${quote(task.practice.familyId)},0,null,true)`).join(',\n')}
on conflict(lesson_id,skill,task_id) do nothing;
commit;
`;
await writeFile('supabase/migrations/20261125000000_l15_grammar_learning_catalog.sql',sql);
console.log('Registered five L15 cards and ten immutable questions.');
